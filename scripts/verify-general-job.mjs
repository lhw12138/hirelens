import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {mkdir} from "node:fs/promises";
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.HIRELENS_PLAYWRIGHT_PATH||"playwright");
const base=process.env.HIRELENS_TEST_URL||"http://localhost:3000";
const browser=await chromium.launch({channel:"msedge",headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on("pageerror",error=>errors.push(error.message));
await mkdir(".impeccable/review",{recursive:true});
let created;
try{
 await page.goto(base+"/login");
 await page.getByRole("textbox",{name:"邮箱"}).fill(process.env.HR_ADMIN_EMAIL||"admin@hirelens.local");
 await page.getByLabel("密码",{exact:true}).fill(process.env.HR_ADMIN_PASSWORD||"hirelens-demo");
 await page.getByRole("button",{name:"进入工作台"}).click();
 await page.waitForURL(base+"/");
 const create=await context.request.post(base+"/api/tasks",{data:{synthetic:false}});
 assert.equal(create.status(),201);
 created=await create.json();
 assert.deepEqual(created.data.criteria,[],"真实任务不应预填任何岗位模板");
 const title="高级后端工程师 · 自动验收";
 const jd="负责 Java 微服务与高并发交易系统的设计、开发和性能优化；要求熟悉 Spring Boot、MySQL、Redis、消息队列和分布式系统，能够定位线上故障并通过压测验证改进效果；与测试、运维协作完成发布和复盘。";
 const parsed=await context.request.post(base+`/api/tasks/${created.id}`,{data:{action:"parse",title,jd,version:created.version},timeout:120000});
 assert.equal(parsed.status(),200,await parsed.text());
 const row=await parsed.json();
 assert.ok(row.data.criteria.length>=3&&row.data.criteria.length<=8);
 assert.equal(row.data.criteria.reduce((sum,item)=>sum+item.weight,0),100);
 assert.match(row.data.criteria.map(item=>`${item.name} ${item.description}`).join(" "),/Java|微服务|分布式|数据库|性能|系统|后端/i);
 await page.goto(base+`/tasks/${created.id}`);
 await page.getByText("简历初筛评分维度",{exact:true}).waitFor();
 await page.getByRole("button",{name:"全部改为自定义"}).click();
 await page.getByLabel("第1项能力名称").waitFor();
 assert.equal(await page.getByLabel("第1项能力名称").inputValue(),"自定义维度 1");
 await page.screenshot({path:".impeccable/review/general-job-desktop.png",fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:".impeccable/review/general-job-mobile.png",fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth),false);
 assert.deepEqual(errors,[]);
 await context.request.delete(base+`/api/tasks/${created.id}`,{data:{version:row.version}});
 console.log(JSON.stringify({status:"PASS",role:title,criteria:row.data.criteria.map(item=>({name:item.name,weight:item.weight})),screenshots:[".impeccable/review/general-job-desktop.png",".impeccable/review/general-job-mobile.png"]},null,2));
}finally{await browser.close();}
